// Подключаем библиотеки для ввода/вывода.
#include <iostream> 
#include <iomanip>

int main() // Объявляем главную функцию.
{
	// Константа для числа π.
	// Используем const, чтобы значение не изменялось во время работы программы.
	// Используем double, так как π - это вещественное число.
	const double PI = 3.14;

	double R; // Создаём переменную для хранения значения радиуса.
	double S; // Создаём переменную для результата значения площади круга.
	double C; // Создаём переменную для результата значения длины окружности.
	// Тип double позволяет хранить вещественные числа, например 1250.50 или 12.5.
	// При работе с double возможна небольшая погрешность представления некоторых дробных чисел.
	// При использовании очень больших чисел типа double возможна потеря точности или переполнение.

	std::cout << "Enter the R: "; // Запрашиваем значение радиуса окружности.
	std::cin >> R; // Считываем введённое значение в переменную R.

	S = PI * static_cast<double>(R) * R; // Пишем формулу площади круга заданного радиуса.
	// Явное приведение: static_cast<double>(R) гарантирует, что R*R вычисляется как double.
	// Приведение к double перед умножением предотвратит целочисленное переполнение и потерю точности.
	C = 2.0 * PI * R; // Пишем формулу длины окружности заданного радиуса.
	// Пишем 2.0 - чтобы явно показать, что умножение вещественное.

	// Форматируем вещественные числа: fixed выводит число в обычном десятичном формате, setprecision(2) оставляет два знака после запятой.
	std::cout << std::fixed << std::setprecision(2) << "Square: " << S << std::endl; // Выводим результат площади круга.
	std::cout << std::fixed << std::setprecision(2) << "Circumference length: " << C << std::endl; // Выводим результат длины окружности.

	return 0; // Успешное завершение программы.
}