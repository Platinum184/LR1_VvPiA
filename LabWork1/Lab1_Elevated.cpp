// Подключаем библиотеки для ввода/вывода
#include <iostream> 
#include <iomanip>
#include <limits>

int main() // Объявляем главную функцию
{
   // Константа для перевода км в мм.
   // Используем const, чтобы значение не изменялось во время работы программы.
    const double mm_in_km = 1000000;

   // Константа для перевода м в мм.
   // Используем const, чтобы значение не изменялось во время работы программы.
    const double mm_in_m = 1000;

   // Константа для перевода см в мм.
   // Используем const, чтобы значение не изменялось во время работы программы.
    const double mm_in_cm = 10;

	double km; // Создаём переменную для хранения значения км
	double m; // Создаём переменную для хранения значения м
	double cm; // Создаём переменную для хранения значения см
	// Используем double, так как км, м и см могут быть дробными числами.
    // Тип double позволяет хранить вещественные числа, например 1250.50 или 12.5.
    // При работе с double возможна небольшая погрешность представления некоторых дробных чисел.
    // При использовании очень больших чисел типа double возможна потеря точности или переполнение.

	std::cout << "Enter the km: "; // Запрашиваем значение км
	std::cin >> km; // Считываем введённое значение в переменную km

    // Проверяем, что пользователь ввёл число.
    if (std::cin.fail())
    {
        // Сбрасываем состояние ошибки ввода.
        std::cin.clear();

        // Удаляем некорректные данные из буфера ввода.
        std::cin.ignore(
            std::numeric_limits<std::streamsize>::max(), '\n');

        std::cout << "Error: a number must be entered."
            << std::endl;

        return 1;
    }

    // Проверяем граничное значение: расстояние не может быть отрицательно.
    if (km < 0)
    {
        std::cout << "Error: distance cannot be negative."
            << std::endl;

        return 1;
    }

	std::cout << "Enter the m: "; // Запрашиваем значение м
	std::cin >> m; // Считываем введённое значение в переменную m

    // Проверяем, что пользователь ввёл число.
    if (std::cin.fail())
    {
        // Сбрасываем состояние ошибки ввода.
        std::cin.clear();

        // Удаляем некорректные данные из буфера ввода.
        std::cin.ignore(
            std::numeric_limits<std::streamsize>::max(), '\n');

        std::cout << "Error: a number must be entered."
            << std::endl;

        return 1;
    }

    // Проверяем граничное значение: расстояние не может быть отрицательно.
    if (m < 0)
    {
        std::cout << "Error: distance cannot be negative."
            << std::endl;

        return 1;
    }

	std::cout << "Enter the cm: "; // Запрашиваем значение см
	std::cin >> cm; // Считываем введённое значение в переменную cm

    // Проверяем, что пользователь ввёл число.
    if (std::cin.fail())
    {
        // Сбрасываем состояние ошибки ввода.
        std::cin.clear();

        // Удаляем некорректные данные из буфера ввода.
        std::cin.ignore(
            std::numeric_limits<std::streamsize>::max(), '\n');

        std::cout << "Error: a number must be entered."
            << std::endl;

        return 1;
    }

    // Проверяем граничное значение: расстояние не может быть отрицательно.
    if (cm < 0)
    {
        std::cout << "Error: distance cannot be negative."
            << std::endl;

        return 1;
    }

	double mm_km = km * mm_in_km; // Создам переменную для перевода км в мм и пишем формулу перевода
	double mm_m = m * mm_in_m; // Создам переменную для перевода м в мм и пишем формулу перевода
	double mm_cm = cm * mm_in_cm; // Создам переменную для перевода см в мм и пишем формулу перевода

	double intotal_mm = mm_km + mm_m + mm_cm; // Пишем формулу суммы для переведённых значений

    // Форматируем вещественные числа: fixed выводит число в обычном десятичном формате, setprecision(2) оставляет два знака после запятой.
	std::cout << std::fixed << std::setprecision(2) << "Mm (total): " << intotal_mm << std::endl; // Выводим результат

	return 0; // Успешное завершение программы
}